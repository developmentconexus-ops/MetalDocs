package main

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strings"
)

// EmitOptions parameterizes Emit so it can render either
// apps/api/cmd/metaldocs-api/httpsurface_gen.go (SurfaceVar "httpSurface",
// TagsVar "specTags") or the internal-e2e variant (Task 12), which needs
// distinct package-level identifiers because both files land in the same
// package.
type EmitOptions struct {
	SurfaceVar string
	TagsVar    string
	// Registry maps a wire capability string (x-authz-capability's value) to
	// the Go constant name declared for it in iam/domain/model.go (e.g.
	// "metrics.view" -> "CapMetricsView"). Built by loadCapabilityRegistry;
	// Validate already proved every declared capability resolves through it.
	Registry map[string]string
	// SkipTypeDecl omits the `type surfaceRule struct {...}` declaration.
	// httpsurface_gen.go and httpsurface_e2e_gen.go (Task 12) land in the
	// same package, so only the first target emitted declares the type;
	// every later target sets this true to avoid a duplicate declaration.
	SkipTypeDecl bool
}

// Emit renders the generated surfaceRule table for one Document. Output is
// fully deterministic: entries are emitted in Key-sorted order and specTags
// in sorted, de-duplicated order, then the whole file is run through
// go/format.Source — determinism is what makes the CI drift gate (Task 5
// step 9/10) meaningful; a non-deterministic emitter would make it flap.
func Emit(d Document, opts EmitOptions) (string, error) {
	type entry struct {
		key string
		op  Operation
	}

	entries := make([]entry, 0, len(d.Operations))
	tagSet := map[string]bool{}
	hasCapability := false
	for _, op := range d.Operations {
		entries = append(entries, entry{key: Key(d, op), op: op})
		if op.Tag != "" {
			tagSet[op.Tag] = true
		}
		if op.Capability != "" {
			hasCapability = true
		}
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].key < entries[j].key })

	tags := make([]string, 0, len(tagSet))
	for t := range tagSet {
		tags = append(tags, t)
	}
	sort.Strings(tags)

	var b strings.Builder
	b.WriteString("// Code generated by cmd/gen-http-surface. DO NOT EDIT.\n\n")
	b.WriteString("package main\n\n")
	b.WriteString("import (\n")
	b.WriteString("\tiamdelivery \"metaldocs/internal/modules/iam/delivery/http\"\n")
	// iamdomain is only referenced when an entry carries a capability
	// (`capability: iamdomain.CapX`); an all-public/all-session-required
	// document (the e2e surface, Task 12) would otherwise import it unused.
	if hasCapability {
		b.WriteString("\tiamdomain \"metaldocs/internal/modules/iam/domain\"\n")
	}
	b.WriteString(")\n\n")

	if !opts.SkipTypeDecl {
		b.WriteString("type surfaceRule struct {\n")
		b.WriteString("\tvisibility iamdelivery.Visibility\n")
		b.WriteString("\tcapability iamdomain.Capability\n")
		b.WriteString("\ttag string\n")
		b.WriteString("\tallowedDuringPasswordChange bool\n")
		b.WriteString("}\n\n")
	}

	fmt.Fprintf(&b, "var %s = map[string]surfaceRule{\n", opts.SurfaceVar)
	for _, e := range entries {
		op := e.op
		fmt.Fprintf(&b, "\t%q: {\n", e.key)

		visibility := "iamdelivery.VisibilityPermissionGuarded"
		switch {
		case op.Public:
			visibility = "iamdelivery.VisibilityPublic"
		case op.CapabilityNone != "":
			visibility = "iamdelivery.VisibilitySessionRequired"
		case op.Capability != "":
			visibility = "iamdelivery.VisibilityPermissionGuarded"
		}
		fmt.Fprintf(&b, "\t\tvisibility: %s,\n", visibility)

		if op.Capability != "" {
			constName, ok := opts.Registry[op.Capability]
			if !ok {
				return "", fmt.Errorf("emit: operation %q declares capability %q, which is not in the registry (Validate should have caught this)", op.ID, op.Capability)
			}
			fmt.Fprintf(&b, "\t\tcapability: iamdomain.%s,\n", constName)
		}

		fmt.Fprintf(&b, "\t\ttag: %q,\n", op.Tag)

		// allowedDuringPasswordChange is separated from the visibility/
		// capability/tag group by a blank line deliberately: gofmt's
		// tabwriter column-aligns a contiguous run of `key: value,` lines,
		// and allowedDuringPasswordChange (27 chars) is far wider than the
		// other keys. Keeping it in the same run would pad "visibility:"
		// and "tag:" out to that width across every entry, including the
		// (common) ones where allowedDuringPasswordChange never appears —
		// a blank line resets the tabwriter's alignment run.
		if op.PasswordChangeAllowed {
			b.WriteString("\n\t\tallowedDuringPasswordChange: true,\n")
		}

		b.WriteString("\t},\n")
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, "var %s = []string{", opts.TagsVar)
	for i, t := range tags {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "%q", t)
	}
	b.WriteString("}\n")

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return "", fmt.Errorf("emit: formatting generated source: %w", err)
	}
	return string(bytes.TrimRight(formatted, "\n")) + "\n", nil
}
