package main

import (
	"strings"
	"testing"
)

func TestEmitShape(t *testing.T) {
	d := Document{Path: "openapi.yaml", ServerBase: "/api/v1", Operations: []Operation{
		{ID: "getMetrics", Method: "GET", Path: "/metrics", Tag: "observability", Capability: "metrics.view"},
		{ID: "checkLiveness", Method: "GET", Path: "/health/live", Tag: "health", Public: true},
		{ID: "getCurrentUser", Method: "GET", Path: "/auth/me", Tag: "auth",
			CapabilityNone: "own principal", PasswordChangeAllowed: true},
	}}
	src, err := Emit(d, EmitOptions{
		SurfaceVar: "httpSurface", TagsVar: "specTags",
		Registry: map[string]string{"metrics.view": "CapMetricsView"},
	})
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"// Code generated by cmd/gen-http-surface. DO NOT EDIT.",
		`"GET /api/v1/metrics": {`,
		"visibility: iamdelivery.VisibilityPermissionGuarded",
		"capability: iamdomain.CapMetricsView",
		`tag:        "observability"`,
		`"GET /api/v1/health/live": {`,
		"visibility: iamdelivery.VisibilityPublic",
		`"GET /api/v1/auth/me": {`,
		"visibility: iamdelivery.VisibilitySessionRequired",
		"allowedDuringPasswordChange: true",
		`var specTags = []string{"auth", "health", "observability"}`,
	} {
		if !strings.Contains(src, want) {
			t.Errorf("emitted source missing %q", want)
		}
	}
}

func TestEmitIsDeterministic(t *testing.T) {
	d := Document{ServerBase: "/api/v1", Operations: []Operation{
		{ID: "b", Method: "GET", Path: "/b", Tag: "z", Public: true},
		{ID: "a", Method: "GET", Path: "/a", Tag: "a", Public: true},
	}}
	o := EmitOptions{SurfaceVar: "httpSurface", TagsVar: "specTags"}
	first, _ := Emit(d, o)
	second, _ := Emit(d, o)
	if first != second {
		t.Fatal("emission is not deterministic; the drift gate would flap")
	}
	if strings.Index(first, `"GET /api/v1/a"`) > strings.Index(first, `"GET /api/v1/b"`) {
		t.Fatal("keys are not sorted; emission must be stable across runs")
	}
}
